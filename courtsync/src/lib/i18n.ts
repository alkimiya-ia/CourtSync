export function t(value: string): string {
  return current === 'es' ? (es[value] ?? value) : value;
}
export function tr(value: string): string {
  if (current === 'en') return value;
  if (es[value]) return es[value];
  // Support common labels containing numbers or team/user names without translating user data.
  return value
    .replace(/\bTracked by /g, 'Registrado por ')
    .replace(/\bPlayer #/g, 'Jugador n.º ')
    .replace(/\bPlayer pts /g, 'Puntos jugadores ')
    .replace(/\bTrack (\d+) players\b/g, 'Seguir $1 jugadores')
    .replace(/\bNo game uses the code\b/g, 'Ningún partido utiliza el código')
    .replace(/\bCheck it with the organizer\./g, 'Consúltalo con el organizador.')
    .replace(/\bRecord stats for one or more players\b/g, 'Registrar estadísticas de uno o varios jugadores')
    .replace(/ · you’ll be backup/g, ' · serás suplente')
    .replace(/ · not synced yet/g, ' · aún sin sincronizar')
    .replace(/ · not tracked/g, ' · sin seguimiento');
}
