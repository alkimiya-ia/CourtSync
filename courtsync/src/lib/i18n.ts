import { useSyncExternalStore } from 'react';

/** UI language only; stored game/player data and event types remain unchanged. */
export type Language = 'es' | 'en';
const STORAGE = 'courtsync:language';
const read = (): Language => {
  try { return localStorage.getItem(STORAGE) === 'en' ? 'en' : 'es'; }
  catch { return 'es'; }
};
let current: Language = read();
const listeners = new Set<() => void>();
export function setLanguage(lang: Language) {
  if (lang === current) return;
  current = lang;
  try { localStorage.setItem(STORAGE, lang); } catch { /* storage unavailable */ }
  document.documentElement.lang = lang;
  listeners.forEach((fn) => fn());
}
export const getLanguage = () => current;
const subscribe = (fn: () => void) => { listeners.add(fn); return () => { listeners.delete(fn); }; };
export function useLanguage(): Language { return useSyncExternalStore(subscribe, getLanguage, () => 'es'); }
